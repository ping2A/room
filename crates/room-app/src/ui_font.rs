/// Width in font columns of `text` (6 per character, minus the last gap).
#[must_use]
pub(crate) fn columns(text: &str) -> u32 {
    (text.chars().count() as u32 * 6).saturating_sub(1)
}

/// Paint `text` at integer scale `k` with its top-left at `(x0, y0)`,
/// calling `plot(x, y)` for every lit pixel.
pub(crate) fn paint(text: &str, x0: i64, y0: i64, k: u32, mut plot: impl FnMut(i64, i64)) {
    for (gi, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5_u32 {
                if bits & (0x10 >> col) == 0 {
                    continue;
                }
                let px = x0 + i64::from((gi as u32 * 6 + col) * k);
                let py = y0 + (row as i64) * i64::from(k);
                for dy in 0..i64::from(k) {
                    for dx in 0..i64::from(k) {
                        plot(px + dx, py + dy);
                    }
                }
            }
        }
    }
}

/// `text` at scale `k` on a filled box with a one-glyph-column margin:
/// `(width, height, RGBA8 pixels)`. Used for small on-screen labels such as
/// the frame-rate counter.
#[must_use]
pub(crate) fn badge(text: &str, k: u32, fg: [u8; 4], bg: [u8; 4]) -> (u32, u32, Vec<u8>) {
    let k = k.max(1);
    let pad = 3 * k;
    let w = columns(text) * k + 2 * pad;
    let h = 7 * k + 2 * pad;
    let mut rgba: Vec<u8> = bg
        .iter()
        .copied()
        .cycle()
        .take((w * h * 4) as usize)
        .collect();
    paint(text, i64::from(pad), i64::from(pad), k, |x, y| {
        if let (Ok(x), Ok(y)) = (u32::try_from(x), u32::try_from(y)) {
            if x < w && y < h {
                let i = ((y * w + x) * 4) as usize;
                rgba[i..i + 4].copy_from_slice(&fg);
            }
        }
    });
    (w, h, rgba)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_badge_is_the_text_plus_its_margin() {
        let (w, h, rgba) = badge("60 FPS", 2, [255; 4], [0, 0, 0, 160]);
        assert_eq!((w, h), (columns("60 FPS") * 2 + 12, 14 + 12));
        assert_eq!(rgba.len(), (w * h * 4) as usize);
        // Corner: background; some pixel: text.
        assert_eq!(&rgba[..4], &[0, 0, 0, 160]);
        assert!(rgba.chunks(4).any(|p| p == [255; 4]));
    }

    #[test]
    fn every_glyph_fits_five_columns_and_letters_differ() {
        let set = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:;-_+/\\()[]<>=!?'\"%#&*@";
        let mut seen = std::collections::BTreeSet::new();
        for ch in set.chars() {
            let g = glyph(ch);
            assert!(g.iter().all(|r| *r < 0x20), "{ch}");
            assert!(g.iter().any(|r| *r != 0), "{ch} is blank");
            assert!(seen.insert(g), "{ch} duplicates another glyph");
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph(' '), [0; 7]);
    }

    #[test]
    fn paint_scales_and_measures() {
        assert_eq!(columns("AB"), 11);
        let mut lit = Vec::new();
        paint("I", 10, 20, 2, |x, y| lit.push((x, y)));
        // 'I' has 3 + 1×5 + 3 = 11 lit cells, each 2×2 at scale 2.
        assert_eq!(lit.len(), 11 * 4);
        assert!(
            lit.iter()
                .all(|&(x, y)| (10..20).contains(&x) && (20..34).contains(&y))
        );
    }
}

//! Internal functions that compile to their own p-code (ACC `InternalFunctions`).

use crate::pcd::*;

/// An internal function: p-code, argument count, how many arguments are
/// required (the rest default to 0), and whether it pushes a result.
pub(crate) struct Builtin {
    pub name: &'static str,
    pub pcode: u32,
    pub argc: u8,
    pub min: u8,
    pub returns: bool,
}

const fn b(name: &'static str, pcode: u32, argc: u8, min: u8, returns: bool) -> Builtin {
    Builtin {
        name,
        pcode,
        argc,
        min,
        returns,
    }
}


/// Value of a missing optional argument.
pub(crate) fn default_arg(name: &str, index: usize) -> i32 {
    match (name.to_ascii_lowercase().as_str(), index) {
        // ChangeLevel(map, pos, flags, skill = -1): keep the current skill.
        ("changelevel", 3) => -1,
        _ => 0,
    }
}

/// `arg` rewritten as a number when it is an unquoted flag expression whose
/// names all contain `_` (`SXF_NOCHECKPOSITION|SXF_SETMASTER`). Plain words
/// (`Gray`, state labels, class names) are left alone.
#[must_use]
pub(crate) fn resolve_flag_arg(arg: &str) -> Option<String> {
    let t = arg.trim();
    if t.is_empty() || t.starts_with('"') || t.parse::<f64>().is_ok() {
        return None;
    }
    let mut saw_name = false;
    for word in t.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_')) {
        if word.is_empty() || word.as_bytes()[0].is_ascii_digit() {
            continue;
        }
        if word.eq_ignore_ascii_case("true") || word.eq_ignore_ascii_case("false") {
            continue;
        }
        if !word.contains('_') {
            return None;
        }
        saw_name = true;
    }
    if !saw_name {
        return None;
    }
    eval_int(t).map(|v| v.to_string())
}

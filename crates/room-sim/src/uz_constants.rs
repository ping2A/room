/// Value of a UZDoom constant (`SXF_NOCHECKPOSITION`, `CHAN_BODY`, …).
#[must_use]
pub(crate) fn constant(name: &str) -> Option<i64> {
    UZ_CONSTANTS
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| UZ_CONSTANTS[i].1)
        .or_else(|| {
            UZ_CONSTANTS
                .iter()
                .find(|(n, _)| n.eq_ignore_ascii_case(name))
                .map(|(_, v)| *v)
        })
}

/// Evaluate a DECORATE integer argument: numbers, UZDoom constants, `true` /
/// `false`, and `| & ^ + - * / << >> ~` with parentheses
/// (`SXF_NOCHECKPOSITION|SXF_TRANSFERPOINTERS`). `None` when any name is unknown.
#[must_use]
pub(crate) fn eval_int(src: &str) -> Option<i64> {
    let toks = tokenize(src)?;
    let mut p = Parser { toks: &toks, i: 0 };
    let v = p.or()?;
    (p.i == toks.len()).then_some(v)
}

#[derive(Clone, Debug, PartialEq)]
enum Tok {
    Num(i64),
    Op(&'static str),
}

fn tokenize(src: &str) -> Option<Vec<Tok>> {
    let b = src.trim().trim_matches('"').as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        if c.is_ascii_whitespace() {
            i += 1;
        } else if c.is_ascii_digit() {
            let start = i;
            if c == b'0' && i + 1 < b.len() && (b[i + 1] == b'x' || b[i + 1] == b'X') {
                i += 2;
                while i < b.len() && b[i].is_ascii_hexdigit() {
                    i += 1;
                }
                let s = std::str::from_utf8(&b[start + 2..i]).ok()?;
                out.push(Tok::Num(i64::from_str_radix(s, 16).ok()?));
            } else {
                while i < b.len() && b[i].is_ascii_digit() {
                    i += 1;
                }
                if i < b.len() && b[i] == b'.' {
                    return None;
                }
                out.push(Tok::Num(
                    std::str::from_utf8(&b[start..i]).ok()?.parse().ok()?,
                ));
            }
        } else if c.is_ascii_alphabetic() || c == b'_' {
            let start = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_') {
                i += 1;
            }
            let name = std::str::from_utf8(&b[start..i]).ok()?;
            let v = match name.to_ascii_lowercase().as_str() {
                "true" => 1,
                "false" => 0,
                _ => constant(name)?,
            };
            out.push(Tok::Num(v));
        } else {
            let two = if i + 1 < b.len() {
                &b[i..i + 2]
            } else {
                &b[i..i + 1]
            };
            let op: &'static str = match two {
                b"<<" => "<<",
                b">>" => ">>",
                _ => match c {
                    b'|' => "|",
                    b'&' => "&",
                    b'^' => "^",
                    b'+' => "+",
                    b'-' => "-",
                    b'*' => "*",
                    b'/' => "/",
                    b'~' => "~",
                    b'(' => "(",
                    b')' => ")",
                    _ => return None,
                },
            };
            i += op.len();
            out.push(Tok::Op(op));
        }
    }
    Some(out)
}

struct Parser<'a> {
    toks: &'a [Tok],
    i: usize,
}

impl Parser<'_> {
    fn peek(&self, op: &str) -> bool {
        matches!(self.toks.get(self.i), Some(Tok::Op(o)) if *o == op)
    }
    fn binary(&mut self, ops: &[&str], next: fn(&mut Self) -> Option<i64>) -> Option<i64> {
        let mut v = next(self)?;
        loop {
            let Some(op) = ops.iter().copied().find(|o| self.peek(o)) else {
                return Some(v);
            };
            self.i += 1;
            let r = next(self)?;
            v = match op {
                "|" => v | r,
                "^" => v ^ r,
                "&" => v & r,
                "<<" => v.checked_shl(u32::try_from(r).ok()?)?,
                ">>" => v.checked_shr(u32::try_from(r).ok()?)?,
                "+" => v.wrapping_add(r),
                "-" => v.wrapping_sub(r),
                "*" => v.wrapping_mul(r),
                "/" => v.checked_div(r)?,
                _ => return None,
            };
        }
    }
    fn or(&mut self) -> Option<i64> {
        self.binary(&["|"], Self::xor)
    }
    fn xor(&mut self) -> Option<i64> {
        self.binary(&["^"], Self::and)
    }
    fn and(&mut self) -> Option<i64> {
        self.binary(&["&"], Self::shift)
    }
    fn shift(&mut self) -> Option<i64> {
        self.binary(&["<<", ">>"], Self::add)
    }
    fn add(&mut self) -> Option<i64> {
        self.binary(&["+", "-"], Self::mul)
    }
    fn mul(&mut self) -> Option<i64> {
        self.binary(&["*", "/"], Self::unary)
    }
    fn unary(&mut self) -> Option<i64> {
        if self.peek("-") {
            self.i += 1;
            return self.unary().map(i64::wrapping_neg);
        }
        if self.peek("+") {
            self.i += 1;
            return self.unary();
        }
        if self.peek("~") {
            self.i += 1;
            return self.unary().map(|v| !v);
        }
        if self.peek("(") {
            self.i += 1;
            let v = self.or()?;
            if !self.peek(")") {
                return None;
            }
            self.i += 1;
            return Some(v);
        }
        match self.toks.get(self.i) {
            Some(Tok::Num(n)) => {
                self.i += 1;
                Some(*n)
            }
            _ => None,
        }
    }
}


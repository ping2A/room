//! Auto-derived known action names for BD0/BD3 `mod check` + case-fold dispatch.

/// Canonical action name if known (case-insensitive).
#[must_use]
pub fn canonical_action_name(name: &str) -> Option<&'static str> {
    if let Some(c) = exact_action_name(name) {
        return Some(c);
    }
    let lower = name.to_ascii_lowercase();
    CANONICAL.iter().find(|(l, _)| *l == lower).map(|(_, c)| *c)
}

/// True when `call_action_args` has an exact arm for `name`.
#[must_use]
pub fn is_known_action(name: &str) -> bool {
    exact_action_name(name).is_some()
}

/// Case-folded lookup (DECORATE is case-insensitive).
#[must_use]
pub fn is_known_action_ci(name: &str) -> bool {
    canonical_action_name(name).is_some()
}

/// Canonical `A_*` names Room dispatches, sorted and de-duplicated.
#[must_use]
pub fn known_action_names() -> Vec<&'static str> {
    let mut names: Vec<&'static str> = CANONICAL.iter().map(|(_, c)| *c).collect();
    names.sort_unstable();
    names.dedup();
    names
}


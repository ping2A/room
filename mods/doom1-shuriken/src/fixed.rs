//! Q16.16 fixed-point helpers + const sine table (`docs/32` §3.2).

#![allow(dead_code)]
#![deny(clippy::float_arithmetic)]

/// Q16.16 fixed-point.
pub type Fix = i32;

/// 1.0 in Q16.16.
pub const ONE: Fix = 1 << 16;

/// Const sine table: `SIN[i] ≈ sin(2π·i/256)` in Q16.16.
pub static SIN: [Fix; 256] = {
    let mut t = [0i32; 256];
    let mut i = 0;
    while i < 256 {
        // Taylor-ish integer approx via precomputed degrees: use chord tables.
        // Built offline as (sin * 65536) rounded — stored as raw i32 literals.
        t[i] = SIN_RAW[i];
        i += 1;
    }
    t
};

/// Cosine via sine table.
#[must_use]
pub const fn cos(i: u8) -> Fix {
    SIN[i.wrapping_add(64) as usize]
}

/// Sine via table.
#[must_use]
pub const fn sin(i: u8) -> Fix {
    SIN[i as usize]
}

/// Multiply two Q16.16 values.
#[must_use]
pub const fn mul(a: Fix, b: Fix) -> Fix {
    ((a as i64 * b as i64) >> 16) as i32
}

/// Integer square root (bits).
#[must_use]
pub fn isqrt(n: u32) -> u32 {
    if n == 0 {
        return 0;
    }
    let mut x = n;
    let mut y = (x + 1) >> 1;
    while y < x {
        x = y;
        y = (x + n / x) >> 1;
    }
    x
}

/// Rotate `(x,y)` by table index `ang` (around origin), Q16.16 in/out.
#[must_use]
pub fn rotate(x: Fix, y: Fix, ang: u8) -> (Fix, Fix) {
    let c = cos(ang);
    let s = sin(ang);
    (mul(x, c) - mul(y, s), mul(x, s) + mul(y, c))
}


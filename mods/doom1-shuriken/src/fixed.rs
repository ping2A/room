#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sin_quadrants() {
        assert_eq!(sin(0), 0);
        assert!(sin(64) > ONE - 100);
        assert_eq!(sin(128), 0);
        assert!(sin(192) < -ONE + 100);
        assert_eq!(cos(0), sin(64));
    }
}
